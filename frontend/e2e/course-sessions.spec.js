  expect(availability[0].available_spots).toBe(0);
  await page.goto('/admin/courses');
  await page.getByRole('row').filter({hasText:service.title}).getByRole('button',{name:'Szerkesztés',exact:true}).click();
  const lockedNotice=page.locator('dialog .cl-error');
  await expect(lockedNotice).toContainText('már foglalás vagy megkezdett fizetés tartozik');
  await expect(lockedNotice).toHaveCSS('color','rgb(132, 40, 59)');
