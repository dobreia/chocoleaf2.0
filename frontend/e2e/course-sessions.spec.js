  await page.locator('dialog').getByRole('button',{name:'Bezárás',exact:true}).click();
  expect((await request.post(api+'/__test/complete/'+payment)).ok()).toBe(true);
  let state=await(await request.get(api+'/__test/state')).json();
  const bookings=state.bookings.filter(b=>b.customer_email==='f06-browser@example.test');
  expect(bookings).toHaveLength(1);expect(Number(bookings[0].total_price)).toBe(78000);
