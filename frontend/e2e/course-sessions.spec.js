import {test,expect} from '@playwright/test';
const api='http://127.0.0.1:3012';
const origin='http://127.0.0.1:5184';
const day=(offset)=>{
  const d=new Date();d.setDate(d.getDate()+offset);d.setHours(12,0,0,0);
  return new Intl.DateTimeFormat('sv-SE',{timeZone:'Europe/Budapest'}).format(d);
};
async function login(page){
  await page.goto('/admin');await page.getByLabel('Email',{exact:true}).fill('demo@example.test');
  await page.getByLabel('Jelszó',{exact:true}).fill('Demo-browser-2026!');
  await page.getByRole('button',{name:'Bejelentkezés',exact:true}).click();
  await expect(page.getByRole('navigation',{name:'Admin navigáció'})).toBeVisible();
}
async function create(page,title,dates,capacity=4){
  await login(page);
  await page.goto('/admin/services');
  await page.getByRole('button',{name:'+ Új szolgáltatás',exact:true}).click();
  const serviceDialog=page.locator('dialog');
  await serviceDialog.getByLabel('Név',{exact:true}).fill(title);
  await serviceDialog.getByLabel('Alap időtartam (óra)',{exact:true}).fill('5');
  await serviceDialog.getByLabel('Ár (Ft)',{exact:true}).fill('39000');
  await serviceDialog.getByLabel('Alap férőhely',{exact:true}).fill(String(capacity));
  for(let i=1;i<dates.length;i++)await serviceDialog.getByRole('button',{name:'+ Új alkalom hozzáadása',exact:true}).click();
  await page.reload();
  await expect(serviceDialog.getByLabel('Alkalmak száma',{exact:true})).toHaveValue(String(dates.length));
  const saved=page.waitForResponse(r=>r.url().endsWith('/api/admin/services') && r.request().method()==='POST');
  await serviceDialog.getByRole('button',{name:'Mentés',exact:true}).click();
  const response=await saved;
  expect(response.ok(),await response.text()).toBe(true);const service=await response.json();
  await expect(serviceDialog).toHaveCount(0);
  await page.goto('/admin/courses');await page.getByRole('button',{name:'+ Új kurzusmeghirdetés',exact:true}).click();
  const dialog=page.locator('dialog');
  await dialog.getByRole('combobox',{name:'Szolgáltatás',exact:true}).selectOption(service.id);
  await expect(dialog.locator('.cl-session-editor')).toHaveCount(dates.length);
  await expect(dialog.getByRole('button',{name:'+ Új alkalom hozzáadása',exact:true})).toHaveCount(0);
  for(let i=0;i<dates.length;i++){
    await dialog.getByLabel(i?`${i+1}. alkalom kezdése (Budapest)`:'Kezdés (Budapest)',{exact:true}).fill(dates[i][0]);
    await dialog.getByLabel(i?`${i+1}. alkalom befejezése (Budapest)`:'Befejezés (Budapest)',{exact:true}).fill(dates[i][1]);
  }
  await page.reload();
  await expect(dialog).toBeVisible();
  await expect(dialog.locator('.cl-session-editor')).toHaveCount(dates.length);
  await dialog.getByRole('button',{name:'Mentés',exact:true}).click();
  await expect(dialog).toHaveCount(0);
  const group=(await(await page.request.get(api+'/api/bookings/availability?courseId='+service.id)).json())[0];
  expect(group.sessions).toHaveLength(dates.length);return {service,group};
}
test('admin advertises three independent sessions, including two on one day; customers see the full package',async({page})=>{
  const first=day(200),last=day(202);
  const {service,group}=await create(page,'F06 háromalkalmas kurzus',[[first+'T10:00',first+'T12:00'],[first+'T14:00',first+'T15:00'],[last+'T10:00',last+'T13:00']]);
  expect(group.price).toBe(39000);
  await page.goto('/courses');
  const card=page.locator('.course-card').filter({has:page.getByRole('heading',{name:service.title,exact:true})});
  await expect(card.locator('.course-booking-notice')).toContainText('Ez egy több alkalmas kurzus.');
  await expect(card.locator('.course-booking-notice')).toContainText('A foglalással az összes alkalmat lefoglalod.');
  await page.goto('/courses/'+service.id);
  await expect(page.locator('.experience-heading .course-booking-notice')).toContainText('A foglalással az összes alkalmat lefoglalod.');
  await expect(page.locator('.experience-page .course-booking-notice')).toHaveCount(1);
  await expect(page.locator('.experience-date .course-booking-notice')).toHaveCount(0);
  await expect(page.locator('.experience-date').first()).toContainText('3 alkalom · összesen 6 óra');
  await expect(page.locator('.experience-date .cl-session-list li')).toHaveCount(3);
  await page.goto(`/courses/${service.id}/book?date=${last}&slot=${group.id}`);
  await expect(page.getByRole('button',{name:last,exact:true})).toHaveAttribute('aria-pressed','true');
  await expect(page.locator('.booking-calendar-form .cl-session-list li')).toHaveCount(3);
  await expect(page.locator('.booking-calendar-form')).toContainText('A jelentkezés mind a(z) 3 alkalomra szól.');
  await page.getByRole('button',{name:first,exact:true}).click();
  await expect(page.locator('.booking-calendar-slot')).toHaveCount(1);
  await page.locator('.booking-calendar-slot').click();
  await expect(page.locator('.booking-calendar-form .cl-session-list li')).toHaveCount(3);
});
