import {test,expect} from '@playwright/test';
const api='http://127.0.0.1:3012';
const options=data=>({headers:{Origin:'http://127.0.0.1:5184'},data});
test('customers filter by booked course, retain cancelled/deleted history and preserve filters and edit drafts',async({page})=>{
  await page.goto('/admin');
  await page.getByLabel('Email',{exact:true}).fill('demo@example.test');
  await page.getByLabel('Jelszó',{exact:true}).fill('Demo-browser-2026!');
  await page.getByRole('button',{name:'Bejelentkezés',exact:true}).click();
  await expect(page.getByRole('navigation',{name:'Admin navigáció'})).toBeVisible();
  const day=n=>new Date(Date.now()+n*86400000).toISOString().slice(0,10)+'T09:00:00Z';
  const services=[],courses=[];
  for(const [index,title] of ['Customer browser A','Customer browser B'].entries()){
    const response=await page.request.post(api+'/api/admin/services',options({title,session_count:index===0?2:1,duration_minutes:90,price:1000,capacity:10}));
    expect(response.ok()).toBe(true);const service=await response.json();services.push(service);
    const scheduled=await page.request.post(api+'/api/admin/courses',options({service_id:service.id,sessions:Array.from({length:service.session_count},(_,n)=>({start_time:day(400+index*10+n*2)}))}));
    expect(scheduled.ok()).toBe(true);courses.push(await scheduled.json());
  }
  const book=async(index,name)=>{
    const response=await page.request.post(api+'/api/admin/bookings',options({courseId:courses[index].id,customerName:name,customerEmail:name.toLowerCase().replaceAll(' ','-')+'@example.test',seats:1}));
    expect(response.ok()).toBe(true);return(await response.json()).booking;
  };
  await book(0,'History Alice');const cancelled=await book(1,'History Alice');await book(1,'History Bob');const deleted=await book(1,'History Carol');
  for(const booking of [cancelled,deleted])expect((await page.request.patch(api+'/api/admin/bookings/'+booking.id,options({status:'cancelled'}))).ok()).toBe(true);
  expect((await page.request.delete(api+'/api/admin/bookings/'+deleted.id,options())).ok()).toBe(true);
  await page.goto('/admin/customers');
  const search=page.getByRole('searchbox',{name:'Keresés',exact:true});
  const service=page.getByRole('combobox',{name:'Foglalt kurzus',exact:true});
  const status=page.getByRole('combobox',{name:'Figyelembe vett foglalások',exact:true});
  const cards=page.locator('.cl-customer-card');
  await search.fill('History');
  await expect(status).toHaveValue('active');
  await expect(cards).toHaveCount(2);
  await service.selectOption(services[0].id);
  await expect(cards).toHaveCount(1);await expect(cards.first().getByRole('heading',{name:'History Alice',exact:true})).toBeVisible();
  await cards.first().getByRole('button',{name:'Foglalási előzmények',exact:true}).click();
  const history=page.getByRole('region',{name:'Foglalási előzmények: history-alice@example.test',exact:true});
  await expect(history.getByText('1/2. alkalom',{exact:true})).toBeVisible();
  await expect(history.getByText('2/2. alkalom',{exact:true})).toBeVisible();
  await expect(history.getByText('Lemondva',{exact:true})).toBeVisible();
  await expect(history.locator('.cl-customer-bookings > li')).toHaveCount(2);
  await page.reload();
  await expect(search).toHaveValue('History');await expect(service).toHaveValue(services[0].id);await expect(history).toBeVisible();
  await status.selectOption('cancelled');
  await expect(cards).toHaveCount(0);
  await expect(page.getByText('Nincs a szűrésnek megfelelő ügyfél.',{exact:true})).toBeVisible();
  await service.selectOption(services[1].id);
  await expect(cards).toHaveCount(2);
  const archived=cards.filter({has:page.getByRole('heading',{name:'History Carol',exact:true})});
  await archived.getByRole('button',{name:'Foglalási előzmények',exact:true}).click();
  await expect(archived.getByText('Törölt foglalás · megőrzött kurzuselőzmény',{exact:true})).toBeVisible();
  await expect(archived.getByRole('link',{name:'Foglalás megnyitása →',exact:true})).toHaveCount(0);
  await archived.getByRole('button',{name:'Szerkesztés',exact:true}).click();
  const dialog=page.locator('dialog');
  await dialog.getByLabel('Név',{exact:true}).fill('History Carol Updated');
  await dialog.getByLabel('Telefon',{exact:true}).fill('+36301234567');
  await dialog.getByLabel('Belső megjegyzés',{exact:true}).fill('Belső ügyféljegyzet\nMásodik sor');
  await page.reload();
  await expect(dialog.getByLabel('Név',{exact:true})).toHaveValue('History Carol Updated');
  await expect(dialog.getByLabel('Belső megjegyzés',{exact:true})).toHaveValue('Belső ügyféljegyzet\nMásodik sor');
  await dialog.getByRole('button',{name:'Mentés',exact:true}).click();
  await expect(dialog).toHaveCount(0);
  await expect(cards.filter({has:page.getByRole('heading',{name:'History Carol Updated',exact:true})})).toContainText('+36301234567');
  await cards.filter({has:page.getByRole('heading',{name:'History Carol Updated',exact:true})}).getByRole('button',{name:'Szerkesztés',exact:true}).click();
  await expect(dialog.getByLabel('Belső megjegyzés',{exact:true})).toHaveValue('Belső ügyféljegyzet\nMásodik sor');
  await dialog.getByRole('button',{name:'Bezárás',exact:true}).click();
  await status.selectOption('all');await expect(cards).toHaveCount(3);
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+2)).toBe(true);
  await page.screenshot({path:'test-results/customer-history-mobile.png',fullPage:true});
});
