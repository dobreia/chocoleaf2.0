import {test,expect} from '@playwright/test';
const api='http://127.0.0.1:3012/api';
const options=data=>({headers:{Origin:'http://127.0.0.1:5184'},data});
test('gift amounts follow actual advertisements, reject removed selections and keep custom purchase available after load errors',async({page})=>{
  await page.goto('/admin');await page.getByLabel('Email',{exact:true}).fill('demo@example.test');await page.getByLabel('Jelszó',{exact:true}).fill('Demo-browser-2026!');
  await page.getByRole('button',{name:'Bejelentkezés',exact:true}).click();await expect(page.getByRole('navigation',{name:'Admin navigáció'})).toBeVisible();
  const service=await(await page.request.post(api+'/admin/services',options({title:'Gift dynamic course',duration_minutes:60,price:1234,capacity:5}))).json();
  const create=async(n,price)=>{
    const response=await page.request.post(api+'/admin/courses',options({service_id:service.id,price,sessions:[{start_time:new Date(Date.now()+(1200+n)*86400000).toISOString()}]}));
    expect(response.ok()).toBe(true);return response.json();
  };
  const first=await create(0,35791),duplicate=await create(2,35791);
  await page.goto('/giftcard');
  const price=page.getByRole('button',{name:/35\s*791 Ft/});await expect(price).toHaveCount(1);await price.click();
  await expect(page.locator('.voucher-total strong')).toHaveText(/35\s*791 Ft/);
  const next=await create(4,88765);
  await page.evaluate(()=>window.dispatchEvent(new Event('focus')));
  await expect(page.getByRole('button',{name:/88\s*765 Ft/})).toBeVisible();
  expect((await page.request.put(api+'/admin/courses/'+next.id,options({price:99991}))).ok()).toBe(true);
  await page.evaluate(()=>window.dispatchEvent(new Event('focus')));
  await expect(page.getByRole('button',{name:/88\s*765 Ft/})).toHaveCount(0);await expect(page.getByRole('button',{name:/99\s*991 Ft/})).toBeVisible();
  expect((await page.request.delete(api+'/admin/courses/'+first.id,options())).ok()).toBe(true);
  await page.evaluate(()=>window.dispatchEvent(new Event('focus')));await expect(price).toHaveCount(1);
  expect((await page.request.delete(api+'/admin/courses/'+duplicate.id,options())).ok()).toBe(true);
  await page.evaluate(()=>window.dispatchEvent(new Event('focus')));await expect(price).toHaveCount(0);
  await expect(page.getByText(/A korábban kiválasztott kurzusár már nem érhető el/)).toBeVisible();
  await expect(page.locator('button[type="submit"]')).toBeDisabled();await expect(page.locator('.voucher-total strong')).toHaveText('–');
  await page.getByRole('button',{name:/^Egyéni összeg/}).click();
  await page.getByRole('textbox',{name:'Egyéni összeg (Ft / utalvány)',exact:true}).fill('12345');
  await page.route('**/api/giftcard/amounts',route=>route.fulfill({status:503,json:{message:'Test failure'}}));
  await page.evaluate(()=>window.dispatchEvent(new Event('focus')));
  await expect(page.getByText('A kurzusárak most nem tölthetők be. Egyéni összeget továbbra is megadhatsz.',{exact:true})).toBeVisible();
  await expect(page.getByRole('textbox',{name:'Egyéni összeg (Ft / utalvány)',exact:true})).toHaveValue('12345');
  await expect(page.locator('.voucher-total strong')).toHaveText(/12\s*345 Ft/);await expect(page.locator('button[type="submit"]')).toBeEnabled();
  await page.route('**/api/giftcard/amounts',route=>route.fulfill({json:[]}));
  await page.evaluate(()=>window.dispatchEvent(new Event('focus')));
  await expect(page.getByText('Jelenleg egyéni összeggel vásárolhatsz utalványt.',{exact:true})).toBeVisible();
  await expect(page.locator('.voucher-amounts button')).toHaveCount(1);
});
