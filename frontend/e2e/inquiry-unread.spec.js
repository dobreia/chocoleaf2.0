import {test,expect} from '@playwright/test';
const api='http://127.0.0.1:3012';
const options=data=>({headers:{Origin:'http://127.0.0.1:5184'},data});
test('menu badge survives refresh, clears only after the list loads, and preserves unseen new arrivals',async({page})=>{
  await page.goto('/admin');
  await page.getByLabel('Email',{exact:true}).fill('demo@example.test');
  await page.getByLabel('Jelszó',{exact:true}).fill('Demo-browser-2026!');
  await page.getByRole('button',{name:'Bejelentkezés',exact:true}).click();
  await expect(page.getByRole('navigation',{name:'Admin navigáció'})).toBeVisible();
  const initial=await(await page.request.get(api+'/api/admin/inquiries')).json();
  expect((await page.request.post(api+'/api/admin/inquiries/read',options({ids:initial.map(item=>item.id)}))).ok()).toBe(true);
  const create=async name=>expect((await page.request.post(api+'/api/inquiries',options({name,email:'badge@example.test',subject:name,message:'Badge test message'}))).ok()).toBe(true);
  await create('Badge first');await create('Badge second');
  await page.reload();
  const badge=page.locator('.cl-nav-unread');
  const menu=page.getByRole('link',{name:/Megkeresések/});
  await expect(badge).toHaveText('2');
  await page.reload();
  await expect(badge).toHaveText('2');
  // A failed list load must not mark unseen messages as read.
  await page.route('**/api/admin/inquiries',route=>route.fulfill({status:503,json:{message:'List unavailable'}}));
  await menu.click();
  await expect(page.getByRole('alert')).toContainText('List unavailable');
  await expect(badge).toHaveText('2');
  await page.unroute('**/api/admin/inquiries');
  await page.getByRole('link',{name:'Áttekintés',exact:true}).click();
  let continueRead;
  const gate=new Promise(resolve=>{continueRead=resolve;});
  let readStarted;
  const started=new Promise(resolve=>{readStarted=resolve;});
  await page.route('**/api/admin/inquiries/read',async route=>{readStarted();await gate;await route.continue();});
  await menu.click();
  await started;
  await expect(page.getByRole('heading',{name:'Badge first',exact:true})).toBeVisible();
  await create('Badge later');
  continueRead();
  await expect(badge).toHaveText('1');
  await expect(page.getByRole('button',{name:'Kezeltnek jelölés',exact:true})).toHaveCount(2);
  await page.unroute('**/api/admin/inquiries/read');
  await page.reload();
  await expect(page.getByRole('heading',{name:'Badge later',exact:true})).toBeVisible();
  await expect(badge).toHaveCount(0);
  const records=await(await page.request.get(api+'/api/admin/inquiries')).json();
  expect(records.filter(item=>item.name.startsWith('Badge ')).every(item=>item.read_at&&item.status==='new')).toBe(true);
  await page.getByRole('link',{name:'Áttekintés',exact:true}).click();
  await page.reload();
  await expect(page.getByRole('navigation',{name:'Admin navigáció'})).toBeVisible();
  await expect(badge).toHaveCount(0);
  await create('Badge newest');
  await page.evaluate(()=>window.dispatchEvent(new Event('focus')));
  await expect(badge).toHaveText('1');
  await menu.click();
  await expect(page.getByRole('heading',{name:'Badge newest',exact:true})).toBeVisible();
  await expect(badge).toHaveCount(0);
});
